#!/usr/bin/env node
/**
 * Builds the stat id -> icon texture table the planner renders from.
 *
 *   node tools/make-stat-icon-table.mjs --assets data/assets --out <file>
 *
 * The pack ships ~300 stat icons under `mmorpg:textures/gui/stat_icons/**`, and the mod names
 * almost all of them after the stat they belong to — `main/armor.png` is `armor`. Nothing
 * declares that mapping, though: `mmorpg_stat` carries a unicode glyph in its `icon` field and
 * no texture path at all, and the stats a player cares about most (health, armour, every
 * resist) are registered in Java with no JSON, so they have neither.
 *
 * So the mapping is the filename, and this writes it down. A generated table rather than a
 * runtime probe because the renderer's `assetUrl` cannot report a miss — it falls back to the
 * mod's own placeholder — so asking it "is there an icon for this stat" always answers yes.
 *
 * Only the folders whose contents are named after stats are read. `game_changers` and `start`
 * are named after keystones and classes, `stat_groups` after sections; those are exported
 * separately for the callers that want them and never folded into the stat table.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

/**
 * The folders that hold one icon per stat, in the order a name is claimed.
 *
 * `main` first because a duplicate name between it and `misc` is the main one: `block_chance`
 * and `int_dmg` are each in both, and `main` holds the larger, lit version the game's own
 * sheet uses. `element_icons` last of the stat-named folders because its five entries are
 * element names (`fire`, `water`) rather than stat ids and would otherwise shadow nothing.
 */
const STAT_FOLDERS = ["main", "misc", "elemental", "restoration", "weapon", "core", "element_icons"];

/** Folders keyed by something other than a stat id, exported under their own names. */
const OTHER_FOLDERS = { game_changers: "GAME_CHANGER_ICONS", start: "START_ICONS" };

function arg(name, fallback) {
  const at = process.argv.indexOf(`--${name}`);
  return at < 0 || at + 1 >= process.argv.length ? fallback : process.argv[at + 1];
}

const assetsDir = resolve(arg("assets", "data/assets"));
const outPath = resolve(arg("out", "packages/app/src/renderer/src/ui/stat-icons.generated.ts"));

const index = JSON.parse(readFileSync(join(assetsDir, "index.json"), "utf8"));
const paths = Object.keys(index.assets ?? {});
if (paths.length === 0) {
  console.error(`No assets in ${join(assetsDir, "index.json")}.`);
  process.exit(1);
}

/** `mmorpg:textures/gui/stat_icons/main/armor.png` -> `["main", "armor"]`. */
function split(path) {
  const m = /gui\/stat_icons\/(?:([a-z_]+)\/)?([^/]+)\.png$/.exec(path);
  return m === null ? null : [m[1] ?? "", m[2]];
}

const stats = new Map();
const others = new Map(Object.keys(OTHER_FOLDERS).map((folder) => [folder, new Map()]));
const groups = new Map();

for (const path of paths.sort()) {
  const groupMatch = /gui\/stat_groups\/([^/]+)\.png$/.exec(path);
  if (groupMatch !== null) {
    groups.set(groupMatch[1], path);
    continue;
  }

  const parts = split(path);
  if (parts === null) continue;
  const [folder, name] = parts;

  const other = others.get(folder);
  if (other !== undefined) {
    other.set(name, path);
    continue;
  }

  // A name with a space in it is one of the three `unused (2).png` placeholders.
  if (!STAT_FOLDERS.includes(folder) || /[^a-z0-9_]/.test(name)) continue;
  const rank = STAT_FOLDERS.indexOf(folder);
  const held = stats.get(name);
  if (held === undefined || rank < held.rank) stats.set(name, { rank, path });
}

function table(entries) {
  return [...entries]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([name, path]) => `  ${JSON.stringify(name)}: ${JSON.stringify(path)},`)
    .join("\n");
}

const out = `// Generated by tools/make-stat-icon-table.mjs — do not edit by hand.
//
// Stat id -> the texture the pack ships for it, resolved by filename across
// ${STAT_FOLDERS.map((f) => `\`${f}\``).join(", ")}.
// Regenerate after re-extracting the assets.
//
// A stat missing from here has no icon of its own; \`ui/stat-look.ts\` is where the aliases and
// the glyph fallback live, and it is the module to read rather than this one.

/** ${stats.size} stats whose icon is named after them. */
export const STAT_ICONS: Record<string, string> = {
${table([...stats].map(([name, held]) => [name, held.path]))}
};

/** The ${groups.size} section icons — \`damage\`, \`defense\`, \`recovery\`. Keyed by section, not by stat. */
export const GROUP_ICONS: Record<string, string> = {
${table(groups)}
};
${Object.entries(OTHER_FOLDERS)
  .map(
    ([folder, constant]) => `
/** The ${others.get(folder).size} \`${folder}\` icons, keyed by their own id rather than by a stat. */
export const ${constant}: Record<string, string> = {
${table(others.get(folder))}
};`,
  )
  .join("\n")}
`;

writeFileSync(outPath, out);
console.log(
  `${stats.size} stat icons, ${groups.size} group icons, ` +
    Object.entries(OTHER_FOLDERS)
      .map(([folder]) => `${others.get(folder).size} ${folder}`)
      .join(", ") +
    ` -> ${outPath}`,
);
